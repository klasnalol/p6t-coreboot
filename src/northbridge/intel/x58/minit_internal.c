u16 x58_minit_cfg_index(u16 ctx_offset)
{
	if (ctx_offset < X58_MINIT_CFG_CTX_BASE ||
	    ctx_offset > X58_MINIT_CFG_CTX_LAST ||
	    ((ctx_offset - X58_MINIT_CFG_CTX_BASE) & 1))
		return 0xffff;

	return cfg_index[(ctx_offset - X58_MINIT_CFG_CTX_BASE) / 2];
}

static bool wait_cmd_clear(pci_devfn_t dev, u32 mask)
{
	unsigned int i;

	for (i = 0; i < MINIT_WAIT_LOOPS; i++) {
		if (!(pci_read_config32(dev, MINIT_PRIVATE_CMD_REG) & mask))
			return true;
		__asm__ __volatile__("pause");
	}

	return false;
}

static u32 value_mask(const struct x58_minit_field_desc *d)
{
	unsigned int width;

	if (d->span <= 2)
		return 0;
	width = d->span - 2;
	return (1U << width) - 1;
}

static void select_private_domain(pci_devfn_t dev, u8 selector)
{
	u32 reg = pci_read_config32(dev, MINIT_SEL_REG);

	reg &= ~MINIT_SELECTOR_MASK;
	reg |= ((u32)selector & 3U) << 25;
	pci_write_config32(dev, MINIT_SEL_REG, reg);
}

static bool read_desc(u8 bus, u8 selector,
		      const struct x58_minit_field_desc *d, u32 *value)
{
	const pci_devfn_t dev = PCI_DEV(bus, 3, 4);
	u32 end;
	u32 read_index;

	if (!d || !value)
		return false;

	select_private_domain(dev, selector);
	if (!wait_cmd_clear(dev, MINIT_PRIVATE_BUSY))
		return false;

	end = (u32)d->bit + d->span - 1;
	read_index = (selector < 3 ? MINIT_CHANNEL_READ_BASE :
		      MINIT_GLOBAL_READ_BASE) - end;
	pci_write_config32(dev, MINIT_PRIVATE_CMD_REG,
			   MINIT_PRIVATE_READ | (read_index & 0xffff));

	if (!wait_cmd_clear(dev, MINIT_PRIVATE_READ))
		return false;
	*value = pci_read_config32(dev, MINIT_PRIVATE_DATA_REG) & value_mask(d);
	return true;
}

static bool write_desc(u8 bus, u8 selector,
		       const struct x58_minit_field_desc *d, u32 value, u8 op)
{
	const pci_devfn_t dev = PCI_DEV(bus, 3, 4);
	u32 end;
	u32 encoded;
	unsigned int shift;

	if (!d)
		return false;

	select_private_domain(dev, selector);
	if (!wait_cmd_clear(dev, MINIT_PRIVATE_BUSY))
		return false;

	/* Preserve x86 shift-count behavior used by MINIT. */
	shift = (d->span - 2) & 31;
	encoded = value & value_mask(d);
	encoded |= (u32)(op + 2) << shift;

	pci_write_config32(dev, MINIT_PRIVATE_DATA_REG, encoded);
	end = (u32)d->bit + d->span - 1;
	pci_write_config32(dev, MINIT_PRIVATE_CMD_REG,
			   MINIT_PRIVATE_WRITE | end);
	return wait_cmd_clear(dev, MINIT_PRIVATE_WRITE);
}

bool x58_minit_read_global(u8 bus, u16 index, u32 *value)
{
	return read_desc(bus, 3, x58_minit_global_desc(index), value);
}

bool x58_minit_read_channel(u8 bus, u8 channel, u16 index, u32 *value)
{
	if (channel >= 3)
		return false;
	return read_desc(bus, channel, x58_minit_channel_desc(index), value);
}

bool x58_minit_write_global(u8 bus, u16 index, u32 value, u8 op)
{
	return write_desc(bus, 3, x58_minit_global_desc(index), value, op);
}

bool x58_minit_write_channel(u8 bus, u8 channel, u16 index, u32 value, u8 op)
{
	if (channel >= 3)
		return false;
	return write_desc(bus, channel, x58_minit_channel_desc(index), value, op);
}
